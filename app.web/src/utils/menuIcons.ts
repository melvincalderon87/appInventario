const LEGACY_SUFFIX_PATTERN = /(20Regular|24Regular|Regular)$/u;

function withoutLegacySuffix(iconName: string) {
  return iconName.replace(LEGACY_SUFFIX_PATTERN, "");
}

function unique(items: string[]) {
  return Array.from(new Set(items.filter(Boolean)));
}

export function getIcon(nombre: string): IconComponent | null {
  const iconName = String(nombre ?? "").trim();
  if (!iconName) return null;

  const baseName = withoutLegacySuffix(iconName);
  const candidates = unique([
    iconName,
    `${iconName}Icon`,
    ICON_ALIASES[iconName],
    baseName,
    `${baseName}Icon`,
    ICON_ALIASES[baseName],
  ]);

  for (const candidate of candidates) {
    const Icon = ICONS[candidate];
    if (Icon) return Icon;
  }

  return null;
}
